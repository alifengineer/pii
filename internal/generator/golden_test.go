func TestGenerate_BasicStruct(t *testing.T) {
	targets := []analyzer.SanitizeTarget{
		{
			StructName: "User",
			Fields: []analyzer.TargetField{
				{Name: "Name", Action: analyzer.ActionCopy},
				{Name: "Phone", Action: analyzer.ActionSanitize},
			},
		},
	}

	buf := new(bytes.Buffer)
	output, err := Generate("basic", targets, buf)
	if err != nil {
		t.Fatal(err)
	}

	got := string(output)
	t.Log("Generated output:\n" + got)

	assertContains(t, got, "// Code generated by pii; DO NOT EDIT.")
	assertContains(t, got, "package basic")
	assertContains(t, got, "func (v User) Sanitize() User {")
	assertContains(t, got, "v.Phone = v.Phone.Sanitize()")
	assertContains(t, got, "return v")
	assertNotContains(t, got, "v.Name")
}

func TestGenerate_NestedStructs(t *testing.T) {
	targets := []analyzer.SanitizeTarget{
		{
			StructName: "ContactInfo",
			Fields: []analyzer.TargetField{
				{Name: "Phone", Action: analyzer.ActionSanitize},
				{Name: "Email", Action: analyzer.ActionSanitize},
			},
		},
		{
			StructName: "User",
			Fields: []analyzer.TargetField{
				{Name: "Name", Action: analyzer.ActionCopy},
				{Name: "ContactInfo", Action: analyzer.ActionSanitize},
				{Name: "Address", Action: analyzer.ActionCopy},
			},
		},
	}

	buf := new(bytes.Buffer)
	output, err := Generate("nested", targets, buf)
	if err != nil {
		t.Fatal(err)
	}

	got := string(output)
	assertContains(t, got, "func (v ContactInfo) Sanitize() ContactInfo {")
	assertContains(t, got, "v.Phone = v.Phone.Sanitize()")
	assertContains(t, got, "v.Email = v.Email.Sanitize()")
	assertContains(t, got, "func (v User) Sanitize() User {")
	assertContains(t, got, "v.ContactInfo = v.ContactInfo.Sanitize()")
}

