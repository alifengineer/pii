func TestIdentifierAllocator(t *testing.T) {
	alloc := newIdentifierAllocator()
	first := alloc.allocate("tmp")
	if first != "tmp" {
		t.Errorf("first = %q, want %q", first, "tmp")
	}
	second := alloc.allocate("tmp")
	if second != "tmp_0" {
		t.Errorf("second = %q, want %q", second, "tmp_0")
	}
	third := alloc.allocate("tmp")
	if third != "tmp_1" {
		t.Errorf("third = %q, want %q", third, "tmp_1")
	}
	other := alloc.allocate("i")
	if other != "i" {
		t.Errorf("other = %q, want %q", other, "i")
	}
}

func TestShouldWrite_FileNotExist(t *testing.T) {
	if !ShouldWrite([]byte("hello"), "/tmp/nonexistent_pi_test_file.go") {
		t.Error("ShouldWrite should return true for nonexistent file")
	}
}

func TestShouldWrite_Unchanged(t *testing.T) {
	path := t.TempDir() + "/test.go"
	content := []byte("package test\n")
	if err := WriteFile(content, path); err != nil {
		t.Fatal(err)
	}
	if ShouldWrite(content, path) {
		t.Error("ShouldWrite should return false for unchanged content")
	}
}

func TestShouldWrite_Changed(t *testing.T) {
	path := t.TempDir() + "/test.go"
	if err := WriteFile([]byte("old"), path); err != nil {
		t.Fatal(err)
	}
	if !ShouldWrite([]byte("new"), path) {
		t.Error("ShouldWrite should return true for changed content")
	}
}

